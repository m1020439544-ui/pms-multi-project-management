const puppeteer = require('puppeteer-core');
const CHROME = 'C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe';
(async () => {
  const browser = await puppeteer.launch({ executablePath: CHROME, headless: 'new', args: ['--no-sandbox'] });
  const page = await browser.newPage();
  const errors = [];
  page.on('console', m => { if (m.type() === 'error') errors.push('console: ' + m.text()); });
  page.on('pageerror', e => errors.push('pageerror: ' + e.message));
  await page.goto('http://localhost:3000', { waitUntil: 'networkidle0' });
  await page.click('button[type="submit"]');
  await page.waitForSelector('.topnav');
  await page.evaluate(() => { location.hash = '#/contracts'; });
  await new Promise(r => setTimeout(r, 1000));
  const all = await page.evaluate(() => ({ options: document.querySelectorAll('#contract-project option').length, rows: document.querySelectorAll('#contract-body .table tbody tr').length }));
  await page.select('#contract-project', 'p001');
  await new Promise(r => setTimeout(r, 1000));
  const single = await page.evaluate(() => ({ value: document.querySelector('#contract-project').value, rows: document.querySelectorAll('#contract-body .table tbody tr').length, text: document.getElementById('contract-body').innerText.slice(0, 300) }));
  console.log(JSON.stringify({ all, single }, null, 2));
  console.log('errors:', errors.length ? errors : 'none');
  await browser.close();
})().catch(e => { console.error(e); process.exit(1); });
